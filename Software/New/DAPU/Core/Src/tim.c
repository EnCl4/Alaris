/*
 * TIM2 is the sample clock of the whole analog chain. It drives no pin and
 * raises no interrupt: its only job is to emit TRGO on every update event so
 * ADC1 starts a scan at an exactly periodic rate.
 *
 * APB1 timer kernel clock = 2 x PCLK1 = 100 MHz. 100 MHz / 97656 = 1024.0026 Hz.
 * 1024 Hz cannot be produced exactly from 100 MHz; the residual 2.6 ppm is
 * carried in ADC_SCAN_RATE_HZ so the FFT bin width stays exact. TIM2 is a
 * 32 bit timer, so no prescaler is needed and the jitter is one 10 ns tick.
 */
